CREATE TABLE IF NOT EXISTS companies (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  city TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS contacts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  company INTEGER REFERENCES companies(id),
  email TEXT NOT NULL,
  phone TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS deals (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  contact INTEGER REFERENCES contacts(id),
  amount DOUBLE PRECISION NOT NULL,
  stage TEXT NOT NULL,
  notes TEXT NOT NULL
);

ALTER TABLE deals
  ADD COLUMN IF NOT EXISTS next_action TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS follow_up_on DATE;

CREATE TABLE IF NOT EXISTS integration_configs (
  provider TEXT PRIMARY KEY CHECK (provider IN ('kommo', 'meeventos')),
  base_url TEXT NOT NULL,
  token_encrypted TEXT NOT NULL,
  last_checked TIMESTAMPTZ
);

ALTER TABLE public.deals ADD COLUMN IF NOT EXISTS company integer REFERENCES public.companies(id);
DO $$
BEGIN
  IF NOT EXISTS (SELECT FROM pg_constraint WHERE conrelid='public.deals'::regclass AND conname='deal_requires_link') THEN
    ALTER TABLE public.deals ADD CONSTRAINT deal_requires_link CHECK (contact IS NOT NULL OR company IS NOT NULL) NOT VALID;
  END IF;
END $$;
CREATE TABLE IF NOT EXISTS public.contact_segments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE,
  criteria jsonb NOT NULL
);
CREATE TABLE IF NOT EXISTS public.deal_stage_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  deal_id integer NOT NULL REFERENCES public.deals(id) ON DELETE CASCADE,
  stage text NOT NULL,
  created boolean NOT NULL,
  occurred_at timestamptz NOT NULL DEFAULT now()
);
CREATE OR REPLACE FUNCTION public.record_crm_deal_stage() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'INSERT' OR NEW.stage IS DISTINCT FROM OLD.stage THEN
    INSERT INTO public.deal_stage_history(deal_id,stage,created)
    VALUES (NEW.id,NEW.stage,TG_OP = 'INSERT');
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS record_crm_deal_stage ON public.deals;
CREATE TRIGGER record_crm_deal_stage AFTER INSERT OR UPDATE OF stage ON public.deals
FOR EACH ROW EXECUTE FUNCTION public.record_crm_deal_stage();
