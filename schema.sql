CREATE SCHEMA IF NOT EXISTS brain;
CREATE SCHEMA IF NOT EXISTS crm;
SET search_path = crm, brain, public;

CREATE TABLE IF NOT EXISTS brain.companies (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  city TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS brain.contacts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  company INTEGER REFERENCES brain.companies(id),
  email TEXT NOT NULL,
  phone TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS crm.deals (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  contact INTEGER REFERENCES brain.contacts(id),
  amount DOUBLE PRECISION NOT NULL,
  stage TEXT NOT NULL,
  notes TEXT NOT NULL
);

ALTER TABLE crm.deals
  ADD COLUMN IF NOT EXISTS next_action TEXT NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS follow_up_on DATE;

CREATE TABLE IF NOT EXISTS crm.integration_configs (
  provider TEXT PRIMARY KEY CHECK (provider IN ('kommo', 'meeventos')),
  base_url TEXT NOT NULL,
  token_encrypted TEXT NOT NULL,
  last_checked TIMESTAMPTZ
);

ALTER TABLE crm.deals ADD COLUMN IF NOT EXISTS company integer REFERENCES brain.companies(id);
DO $$
BEGIN
  IF NOT EXISTS (SELECT FROM pg_constraint WHERE conrelid='crm.deals'::regclass AND conname='deal_requires_link') THEN
    ALTER TABLE crm.deals ADD CONSTRAINT deal_requires_link CHECK (contact IS NOT NULL OR company IS NOT NULL) NOT VALID;
  END IF;
END $$;
CREATE TABLE IF NOT EXISTS crm.contact_segments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE,
  criteria jsonb NOT NULL
);
CREATE TABLE IF NOT EXISTS crm.deal_stage_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  deal_id integer NOT NULL REFERENCES crm.deals(id) ON DELETE CASCADE,
  stage text NOT NULL,
  created boolean NOT NULL,
  occurred_at timestamptz NOT NULL DEFAULT now()
);
CREATE OR REPLACE FUNCTION crm.record_crm_deal_stage() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'INSERT' OR NEW.stage IS DISTINCT FROM OLD.stage THEN
    INSERT INTO crm.deal_stage_history(deal_id,stage,created)
    VALUES (NEW.id,NEW.stage,TG_OP = 'INSERT');
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS record_crm_deal_stage ON crm.deals;
CREATE TRIGGER record_crm_deal_stage AFTER INSERT OR UPDATE OF stage ON crm.deals
FOR EACH ROW EXECUTE FUNCTION crm.record_crm_deal_stage();

CREATE TABLE IF NOT EXISTS crm.staffing_events (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 160),
  starts_at timestamptz NOT NULL,
  ends_at timestamptz NOT NULL CHECK (ends_at > starts_at),
  location text NOT NULL DEFAULT '',
  group_url text NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS crm.staffing_roles (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id integer NOT NULL REFERENCES crm.staffing_events(id) ON DELETE CASCADE,
  name text NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 120),
  capacity integer NOT NULL CHECK (capacity BETWEEN 1 AND 999),
  UNIQUE(event_id, name)
);
CREATE TABLE IF NOT EXISTS crm.staffing_assignments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_id integer NOT NULL REFERENCES crm.staffing_roles(id) ON DELETE CASCADE,
  contact_id integer NOT NULL REFERENCES brain.contacts(id),
  status text NOT NULL DEFAULT 'invited' CHECK (status IN ('invited','confirmed','declined')),
  responded_at timestamptz,
  UNIQUE(role_id, contact_id)
);
ALTER TABLE crm.staffing_assignments ADD COLUMN IF NOT EXISTS invite_hash text;
CREATE UNIQUE INDEX IF NOT EXISTS staffing_invitation_tokens ON crm.staffing_assignments(invite_hash) WHERE invite_hash IS NOT NULL;
CREATE INDEX IF NOT EXISTS staffing_confirmed_contacts ON crm.staffing_assignments(contact_id) WHERE status = 'confirmed';
