ALTER TABLE crm.deals ADD COLUMN IF NOT EXISTS company integer REFERENCES brain.companies(id);
DO $$
BEGIN
  IF NOT EXISTS (SELECT FROM pg_constraint WHERE conrelid='crm.deals'::regclass AND conname='deal_requires_link') THEN
    ALTER TABLE crm.deals ADD CONSTRAINT deal_requires_link CHECK (contact IS NOT NULL OR company IS NOT NULL) NOT VALID;
  END IF;
END $$;
CREATE TABLE IF NOT EXISTS crm.contact_segments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE,
  criteria jsonb NOT NULL
);
CREATE TABLE IF NOT EXISTS crm.deal_stage_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  deal_id integer NOT NULL REFERENCES crm.deals(id) ON DELETE CASCADE,
  stage text NOT NULL,
  created boolean NOT NULL,
  occurred_at timestamptz NOT NULL DEFAULT now()
);
CREATE OR REPLACE FUNCTION crm.record_crm_deal_stage() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'INSERT' OR NEW.stage IS DISTINCT FROM OLD.stage THEN
    INSERT INTO crm.deal_stage_history(deal_id,stage,created)
    VALUES (NEW.id,NEW.stage,TG_OP = 'INSERT');
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS record_crm_deal_stage ON crm.deals;
CREATE TRIGGER record_crm_deal_stage AFTER INSERT OR UPDATE OF stage ON crm.deals
FOR EACH ROW EXECUTE FUNCTION crm.record_crm_deal_stage();
