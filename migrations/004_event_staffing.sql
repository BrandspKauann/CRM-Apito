BEGIN;
CREATE TABLE IF NOT EXISTS public.staffing_events (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 160),
  starts_at timestamptz NOT NULL,
  ends_at timestamptz NOT NULL CHECK (ends_at > starts_at),
  location text NOT NULL DEFAULT '',
  group_url text NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS public.staffing_roles (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id integer NOT NULL REFERENCES public.staffing_events(id) ON DELETE CASCADE,
  name text NOT NULL CHECK (length(trim(name)) BETWEEN 1 AND 120),
  capacity integer NOT NULL CHECK (capacity BETWEEN 1 AND 999),
  UNIQUE(event_id, name)
);
CREATE TABLE IF NOT EXISTS public.staffing_assignments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_id integer NOT NULL REFERENCES public.staffing_roles(id) ON DELETE CASCADE,
  contact_id integer NOT NULL REFERENCES public.contacts(id),
  status text NOT NULL DEFAULT 'invited' CHECK (status IN ('invited','confirmed','declined')),
  responded_at timestamptz,
  UNIQUE(role_id, contact_id)
);
ALTER TABLE public.staffing_assignments ADD COLUMN IF NOT EXISTS invite_hash text;
CREATE UNIQUE INDEX IF NOT EXISTS staffing_invitation_tokens ON public.staffing_assignments(invite_hash) WHERE invite_hash IS NOT NULL;
CREATE INDEX IF NOT EXISTS staffing_confirmed_contacts ON public.staffing_assignments(contact_id) WHERE status = 'confirmed';
COMMIT;
